#include "../minishell.h"

int	built_in(t_cmd *cmd)
{
	if(ft_strlen(cmd->arg[0]) >= 4 && ft_strncmp(cmd->arg[0], "echo", 4) == 0)
	{
		echo(cmd);
		return (VALID);
	}
	return (ERROR);	
}
